/**
 * SEO audit of the built site (or the live site with --live).
 *
 * For every page it records the title, meta description, robots meta,
 * canonical, hreflang links, H1s and whether the page is in the sitemap, then
 * fails (exit 1) on the problems that keep pages out of Google or confuse it:
 *
 *   - a sitemap page is noindex, or missing
 *   - a page outside the sitemap is indexable
 *   - an hreflang target is missing, not indexable or not reciprocal
 *   - a page has zero or several H1s, or an H1 contains a <script>
 *   - two indexable pages share a title
 *
 * Redirect pages (Astro writes a meta-refresh page for each `redirects` entry
 * in a static build) are listed with their target, not treated as pages.
 *
 * Usage:
 *   node scripts/seo-audit.mjs                 audit dist/ after `astro build`
 *   node scripts/seo-audit.mjs --live          audit https://pickmysaas.com
 *   node scripts/seo-audit.mjs --live --base=https://example.com
 *   node scripts/seo-audit.mjs --out=path.md   write the report somewhere else
 *   node scripts/seo-audit.mjs --no-write      print only
 *
 * No dependencies: the HTML is generated by our own templates, so targeted
 * regular expressions are enough and keep the script runnable anywhere.
 */
/* eslint-disable no-console -- a command-line report */
import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';

const ROOT = process.cwd();
const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);
const option = (name) => args.find((a) => a.startsWith(`--${name}=`))?.split('=').slice(1).join('=');

const LIVE = flag('live');
const BASE = (option('base') || 'https://pickmysaas.com').replace(/\/$/, '');
const today = new Date().toISOString().slice(0, 10);
const OUT_FILE =
  option('out') || join('docs', 'seo', 'implementation', `audit-${today}${LIVE ? '-live' : ''}.md`);

// --- helpers ------------------------------------------------------------------

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

async function walk(directory, match) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) found.push(...(await walk(path, match)));
    else if (match(entry.name)) found.push(path);
  }
  return found;
}

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', mdash: '—', ndash: '–' };
function decode(text) {
  return text
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&([a-z]+);/gi, (m, name) => ENTITIES[name.toLowerCase()] ?? m);
}

const clean = (html) => decode(html.replace(/<[^>]*>/g, ' ')).replace(/\s+/g, ' ').trim();

/** Attribute value from a single tag string. */
function attr(tag, name) {
  const m = tag.match(new RegExp(`\\s${name}\\s*=\\s*("([^"]*)"|'([^']*)'|([^\\s>]+))`, 'i'));
  return m ? decode(m[2] ?? m[3] ?? m[4] ?? '') : null;
}

/** Path part of a URL on this site, normalised; null for other hosts. */
function toPath(url, base = BASE) {
  try {
    const u = new URL(url, base);
    if (u.origin !== new URL(base).origin) return null;
    return decodeURI(u.pathname);
  } catch {
    return null;
  }
}

// --- page parsing -------------------------------------------------------------

function parsePage(html) {
  const head = html.match(/<head[\s\S]*?<\/head>/i)?.[0] ?? html;
  const tags = (re) => [...head.matchAll(re)].map((m) => m[0]);

  const refresh = tags(/<meta[^>]+http-equiv\s*=\s*["']?refresh[^>]*>/gi)[0];
  const refreshTarget = refresh ? (attr(refresh, 'content') || '').match(/url\s*=\s*(.+)$/i)?.[1]?.trim() : null;

  const metas = tags(/<meta\b[^>]*>/gi);
  const links = tags(/<link\b[^>]*>/gi);
  const metaNamed = (name) => metas.find((t) => (attr(t, 'name') || '').toLowerCase() === name);

  const title = clean(head.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1] ?? '');
  const description = attr(metaNamed('description') ?? '', 'content');
  const robots = attr(metaNamed('robots') ?? '', 'content');
  const canonical = attr(links.find((t) => /rel\s*=\s*["']?canonical/i.test(t)) ?? '', 'href');
  const hreflang = links
    .filter((t) => /rel\s*=\s*["']?alternate/i.test(t) && attr(t, 'hreflang'))
    .map((t) => ({ lang: attr(t, 'hreflang'), href: attr(t, 'href') }));

  const h1Blocks = [...html.matchAll(/<h1\b[^>]*>([\s\S]*?)<\/h1>/gi)].map((m) => m[1]);
  const h1s = h1Blocks.map((inner) => ({
    text: clean(inner.replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<style[\s\S]*?<\/style>/gi, ' ')),
    hasScript: /<script\b/i.test(inner),
  }));

  return { refreshTarget, title, description, robots, canonical, hreflang, h1s };
}

const isNoindex = (robots) => /\bnoindex\b|\bnone\b/i.test(robots || '');

// --- collect the pages ----------------------------------------------------------

async function findOutputDir() {
  for (const candidate of ['dist/client', 'dist']) {
    const path = join(ROOT, candidate);
    if (await exists(join(path, 'index.html'))) return path;
  }
  return null;
}

/** Sitemap paths, from local files or the live site. */
async function readSitemap(outDir) {
  const read = async (name) => {
    if (LIVE) {
      const res = await fetch(`${BASE}/${name}`);
      return res.ok ? res.text() : null;
    }
    const path = join(outDir, name);
    return (await exists(path)) ? readFile(path, 'utf8') : null;
  };
  const locs = (xml) => [...xml.matchAll(/<loc>([\s\S]*?)<\/loc>/g)].map((m) => decode(m[1].trim()));

  const index = await read('sitemap-index.xml');
  const files = index ? locs(index).map((u) => new URL(u).pathname.replace(/^\//, '')) : ['sitemap-0.xml'];
  const paths = [];
  for (const file of files) {
    const xml = await read(file);
    if (!xml) continue;
    for (const loc of locs(xml)) paths.push(toPath(loc, new URL(loc).origin));
  }
  return { files, paths: paths.filter(Boolean) };
}

function fileToPath(outDir, file) {
  const rel = relative(outDir, file).split(sep).join('/');
  if (rel === 'index.html') return '/';
  if (rel.endsWith('/index.html')) return `/${rel.slice(0, -'index.html'.length)}`;
  return `/${rel}`;
}

async function collectLocal(outDir) {
  const files = await walk(outDir, (name) => name.endsWith('.html'));
  const pages = new Map();
  for (const file of files) {
    const path = fileToPath(outDir, file);
    const html = await readFile(file, 'utf8');
    pages.set(path, { path, status: 200, xRobots: null, ...parsePage(html) });
  }
  // Server-side redirects (the Cloudflare and Netlify adapters write Astro's
  // `redirects` here instead of meta-refresh pages).
  const redirectsFile = join(outDir, '_redirects');
  if (await exists(redirectsFile)) {
    for (const line of (await readFile(redirectsFile, 'utf8')).split('\n')) {
      const [from, to, code] = line.trim().split(/\s+/);
      if (!from || from.startsWith('#') || !to || !from.endsWith('/') || pages.has(from)) continue;
      pages.set(from, { path: from, status: Number(code) || 301, redirectTo: to });
    }
  }
  return pages;
}

async function collectLive(paths) {
  const pages = new Map();
  const queue = [...new Set(paths)];
  const worker = async () => {
    while (queue.length) {
      const path = queue.shift();
      try {
        const res = await fetch(`${BASE}${encodeURI(path)}`, {
          redirect: 'manual',
          headers: { 'User-Agent': 'seo-audit-script' },
        });
        const page = { path, status: res.status, xRobots: res.headers.get('x-robots-tag') };
        if (res.status >= 300 && res.status < 400) {
          page.redirectTo = toPath(res.headers.get('location') || '', `${BASE}${path}`);
        } else if (res.ok && (res.headers.get('content-type') || '').includes('html')) {
          Object.assign(page, parsePage(await res.text()));
        }
        pages.set(path, page);
      } catch (error) {
        pages.set(path, { path, status: 0, error: String(error) });
      }
    }
  };
  await Promise.all(Array.from({ length: 6 }, worker));
  return pages;
}

// --- audit ----------------------------------------------------------------------

const outDir = await findOutputDir();
if (!LIVE && !outDir) {
  console.error('seo-audit: no build output found. Run `astro build` first, or pass --live.');
  process.exit(1);
}

const sitemap = await readSitemap(outDir);
const sitemapSet = new Set(sitemap.paths);
let pages;
if (LIVE) {
  // Audit every sitemap URL plus every page the local build knows about, so
  // pages that should be out of the index (tags, blog, redirects) are checked too.
  const localPaths = outDir ? [...(await collectLocal(outDir)).keys()] : [];
  pages = await collectLive([...sitemap.paths, ...localPaths.filter((p) => p.endsWith('/'))]);
} else {
  pages = await collectLocal(outDir);
}

const errors = [];
const warnings = [];
const err = (path, message) => errors.push({ path, message });
const warn = (path, message) => warnings.push({ path, message });

for (const page of pages.values()) {
  page.inSitemap = sitemapSet.has(page.path);
  page.isRedirect = Boolean(page.refreshTarget || page.redirectTo);
  page.isHtml = page.title !== undefined;
  if (page.refreshTarget) page.redirectTo = toPath(page.refreshTarget, `${BASE}${page.path}`) ?? page.refreshTarget;
  page.noindex = isNoindex(page.robots) || isNoindex(page.xRobots);
  page.indexable = page.status === 200 && page.isHtml && !page.isRedirect && !page.noindex;
}

// Error pages are expected to be outside the sitemap.
const isErrorPage = (path) => /^\/(\w{2}\/)?(404|500)(\.html|\/)$/.test(path);

if (sitemap.paths.length === 0) err('sitemap', 'no sitemap URLs found');

for (const path of sitemap.paths) {
  const page = pages.get(path);
  if (!page) err(path, 'in the sitemap but not found');
  else if (page.isRedirect) err(path, `in the sitemap but redirects to ${page.redirectTo}`);
  else if (page.status !== 200) err(path, `in the sitemap but returns ${page.status}`);
  else if (page.noindex) err(path, 'in the sitemap but noindex');
}

for (const page of pages.values()) {
  if (!page.isHtml || page.isRedirect) continue;
  if (!page.inSitemap && page.indexable && !isErrorPage(page.path)) {
    err(page.path, 'indexable but not in the sitemap');
  }
  if (!page.indexable) continue;

  // H1s
  if (page.h1s.length === 0) err(page.path, 'no H1');
  if (page.h1s.length > 1) err(page.path, `${page.h1s.length} H1s`);
  if (page.h1s.some((h) => h.hasScript)) err(page.path, 'H1 contains a <script>');
  if (page.h1s.some((h) => !h.text)) err(page.path, 'empty H1');

  // Title and description
  if (!page.title) err(page.path, 'no <title>');
  else if ([...page.title].length > 65) warn(page.path, `title is ${[...page.title].length} characters`);
  const d = page.description ? [...page.description].length : 0;
  if (!d) warn(page.path, 'no meta description');
  else if (d > 160) warn(page.path, `meta description is ${d} characters`);
  else if (d < 70) warn(page.path, `meta description is only ${d} characters`);

  // Canonical
  const canonicalPath = page.canonical ? toPath(page.canonical) : null;
  if (!page.canonical) warn(page.path, 'no canonical');
  else if (canonicalPath !== page.path) warn(page.path, `canonical points to ${page.canonical}`);

  // hreflang
  if (page.hreflang.length) {
    const own = page.hreflang.filter((h) => h.lang !== 'x-default');
    if (!own.some((h) => toPath(h.href) === page.path)) err(page.path, 'hreflang set does not include the page itself');
    const xd = page.hreflang.find((h) => h.lang === 'x-default');
    const en = own.find((h) => h.lang === 'en');
    if (!xd) warn(page.path, 'hreflang set has no x-default');
    else if (en && toPath(xd.href) !== toPath(en.href)) warn(page.path, 'x-default does not point to the English version');
    for (const alt of own) {
      const targetPath = toPath(alt.href);
      if (targetPath === page.path) continue;
      const target = targetPath ? pages.get(targetPath) : null;
      if (!target) {
        err(page.path, `hreflang ${alt.lang} → ${alt.href} does not exist`);
      } else if (!target.indexable) {
        err(page.path, `hreflang ${alt.lang} → ${targetPath} is not indexable`);
      } else if (!target.hreflang?.some((h) => toPath(h.href) === page.path)) {
        err(page.path, `hreflang ${alt.lang} → ${targetPath} does not point back`);
      }
    }
  }
}

// Duplicate titles among indexable pages
const byTitle = new Map();
for (const page of pages.values()) {
  if (!page.indexable || !page.title) continue;
  byTitle.set(page.title, [...(byTitle.get(page.title) || []), page.path]);
}
for (const [title, paths] of byTitle) {
  if (paths.length > 1) err(paths.join(', '), `share the title "${title}"`);
}

// --- report ---------------------------------------------------------------------

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const sorted = [...pages.values()]
  .filter((p) => p.isHtml || p.isRedirect || p.status !== 200)
  .sort((a, b) => Number(b.inSitemap) - Number(a.inSitemap) || a.path.localeCompare(b.path));

const lines = [];
lines.push(`# SEO audit · ${today} · ${LIVE ? `live (${BASE})` : 'build (dist)'}`);
lines.push('');
lines.push(
  `Generated by \`node scripts/seo-audit.mjs${LIVE ? ' --live' : ''}\`. ` +
    `${sitemap.paths.length} sitemap URLs (${sitemap.files.join(', ')}), ${sorted.length} pages checked, ` +
    `**${errors.length} errors**, ${warnings.length} warnings.`,
);
lines.push('');
lines.push('## Errors');
lines.push('');
lines.push(errors.length ? errors.map((e) => `- \`${e.path}\`: ${e.message}`).join('\n') : 'None.');
lines.push('');
lines.push('## Warnings');
lines.push('');
lines.push(warnings.length ? warnings.map((w) => `- \`${w.path}\`: ${w.message}`).join('\n') : 'None.');
lines.push('');
lines.push('## Pages');
lines.push('');
lines.push('| URL | Sitemap | Status | Robots | Title (chars) | Desc chars | Canonical | hreflang | H1s |');
lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const p of sorted) {
  if (p.isRedirect) {
    lines.push(`| \`${p.path}\` | ${p.inSitemap ? 'yes' : 'no'} | redirect → \`${p.redirectTo}\` | | | | | | |`);
    continue;
  }
  if (!p.isHtml) {
    lines.push(`| \`${p.path}\` | ${p.inSitemap ? 'yes' : 'no'} | ${p.status}${p.error ? ` ${esc(p.error)}` : ''} | | | | | | |`);
    continue;
  }
  const canonical = p.canonical ? (toPath(p.canonical) === p.path ? 'self' : `\`${esc(p.canonical)}\``) : '—';
  const hreflang = p.hreflang.length
    ? p.hreflang.map((h) => `${h.lang}: \`${esc(toPath(h.href) ?? h.href)}\``).join('<br>')
    : '—';
  const h1 = p.h1s.length
    ? p.h1s.map((h) => `${esc(h.text)}${h.hasScript ? ' **[script]**' : ''}`).join('<br>')
    : '**none**';
  lines.push(
    `| \`${p.path}\` | ${p.inSitemap ? 'yes' : 'no'} | ${p.status} | ${esc(p.robots || '—')}${p.xRobots ? ` (header: ${esc(p.xRobots)})` : ''} | ` +
      `${esc(p.title)} (${[...(p.title || '')].length}) | ${p.description ? [...p.description].length : 0} | ${canonical} | ${hreflang} | ${h1} |`,
  );
}
const report = `${lines.join('\n')}\n`;

console.log(`seo-audit: ${sitemap.paths.length} sitemap URLs, ${sorted.length} pages, ${errors.length} errors, ${warnings.length} warnings`);
for (const e of errors) console.log(`  ERROR ${e.path}: ${e.message}`);
for (const w of warnings) console.log(`  warn  ${w.path}: ${w.message}`);

if (!flag('no-write')) {
  await mkdir(dirname(join(ROOT, OUT_FILE)), { recursive: true });
  await writeFile(join(ROOT, OUT_FILE), report, 'utf8');
  console.log(`seo-audit: report written to ${OUT_FILE}`);
}

process.exit(errors.length ? 1 : 0);
